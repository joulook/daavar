#!/usr/bin/env python3
"""Compact digest of the campaign CSVs for an evaluation-plan review.

Reads PLDI/tex/tables/campaign-*.csv (produced by tables.py) and writes a markdown
digest: per mode, per (program, variant, spec, model) ladder, one line per size with
graph counts, wall time, peak memory, verdict. Plus a per-program summary with the
largest finished graph count, the first timed-out size, and whether the communication
model changes the counts.
"""
import csv, sys, re
from collections import defaultdict, OrderedDict

TD = sys.argv[1]
OUT = sys.argv[2]
MODES = OrderedDict([
    ("stateful", "C1 stateful (TraceForge, Rust spec / Rust impl, 16 threads)"),
    ("stateless", "C2 stateless (TraceForge, Rust/Rust, 16 threads)"),
    ("offline-tf", "C3J offline (TraceForge export+join, Rust/Rust)"),
    ("online-rust-impl", "XON2 online (TraceForge Rust impl against Java spec export)"),
    ("online-java-impl", "XON1 online (JMC Java impl against Rust spec export)"),
    ("offline-rust-spec", "XJ1 offline (Rust spec export, Java impl export, join)"),
    ("offline-java-spec", "XJ2 offline (Java spec export, Rust impl export, join)"),
])

def sz(s):
    return tuple(int(x) for x in re.findall(r"-?\d+", s)) or (0,)

def num(s):
    try: return float(s)
    except: return None

def fmt_g(s):
    n = num(s)
    if n is None or s == "": return "-"
    n = int(n)
    if n >= 1_000_000: return f"{n/1e6:.1f}M"
    if n >= 10_000: return f"{n/1e3:.0f}k"
    return str(n)

rows_by_mode = {}
for m in MODES:
    with open(f"{TD}/campaign-{m}.csv") as f:
        rows_by_mode[m] = list(csv.DictReader(f))

out = []
summary = defaultdict(lambda: {"maxG": 0, "maxG_where": "", "timeouts": set(), "models": set(), "modes": set(), "sizes": set()})
model_effect = defaultdict(dict)   # (program,variant,spec,size) -> model -> impl graphs (stateful)

for m, title in MODES.items():
    out.append(f"\n## {title}\n")
    groups = defaultdict(list)
    for r in rows_by_mode[m]:
        groups[(r["program"], r["variant"], r["spec"], r["model"])].append(r)
    for key in sorted(groups):
        prog, var, spec, model = key
        rs = sorted(groups[key], key=lambda r: sz(r["size"]))
        label = prog + (f" {var}" if var else "") + (f" spec={spec}" if spec else "") + f" [{model}]"
        cells = []
        for r in rs:
            v = r["verdict"]
            g = f"{fmt_g(r['spec graphs'])}/{fmt_g(r['impl graphs'])}"
            t = r["wall s"]; mem = r["peak MB"]
            extra = ""
            if m == "stateless" and r.get("sweeps"):
                extra = f" sw={r['sweeps']} Gexpl={fmt_g(r['spec graphs explored'])}"
            if m.startswith("offline") and r.get("join s"):
                extra = f" exp={r['spec export s']}/{r['impl export s']} join={r['join s']}"
            star = "" if r["expected"] in ("", v) or v in ("t/o", "oom") else " !!EXPECTED " + r["expected"]
            cells.append(f"  - {r['size']}: G={g} T={t} M={mem} {v}{extra}{star}")
            s = summary[(prog, var, spec)]
            s["models"].add(model); s["modes"].add(m); s["sizes"].add(r["size"])
            gi = num(r["impl graphs"]) or 0; gs = num(r["spec graphs"]) or 0
            if v in ("conforms", "violation") and max(gi, gs) > s["maxG"]:
                s["maxG"] = max(gi, gs); s["maxG_where"] = f"{m} {r['size']} [{model}] T={t}"
            if v in ("t/o", "oom"):
                s["timeouts"].add(f"{m}:{r['size']}[{model}]")
            if m == "stateful" and v in ("conforms", "violation"):
                model_effect[(prog, var, spec, r["size"])][model] = (gs, gi)
        out.append(f"- **{label}**")
        out.extend(cells)

# summary
head = ["\n# Per-program summary\n",
        "| program | variant | spec | models | modes run | sizes | largest finished G | where | timeouts |",
        "|---|---|---|---|---|---|---|---|---|"]
for key in sorted(summary):
    s = summary[key]
    head.append(f"| {key[0]} | {key[1]} | {key[2]} | {','.join(sorted(s['models']))} | {len(s['modes'])} | {len(s['sizes'])} | {fmt_g(str(s['maxG']))} | {s['maxG_where']} | {'; '.join(sorted(s['timeouts'])) or '-'} |")

# model effect
me = ["\n# Does the communication model change the counts? (stateful, same program/size)\n",
      "| program | variant | spec | size | per-model (G_spec,G_impl) | same? |", "|---|---|---|---|---|---|"]
for k in sorted(model_effect):
    d = model_effect[k]
    if len(d) < 2: continue
    vals = set(d.values())
    me.append(f"| {k[0]} | {k[1]} | {k[2]} | {k[3]} | " + ", ".join(f"{m}:({fmt_g(str(a))},{fmt_g(str(b))})" for m, (a, b) in sorted(d.items())) + f" | {'yes' if len(vals)==1 else 'NO'} |")

with open(OUT, "w") as f:
    f.write("# Campaign data digest (generated by daavar/scripts/digest.py from PLDI/tex/tables/campaign-*.csv)\n")
    f.write("G = spec graphs / impl graphs; T = wall seconds; M = peak MB; t/o = 3600 s limit (c48h rows: 48 h). Only rows the tables keep (one per instance, highest thread count, latest pin).\n")
    f.write("\n".join(head)); f.write("\n"); f.write("\n".join(me)); f.write("\n"); f.write("\n".join(out)); f.write("\n")
print("digest written", OUT)
