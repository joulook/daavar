#!/usr/bin/env python3
"""The TiKV study table of the paper (Phase B): the two ports against S_dt and against each other, Offline, with the
Decide post-pass verdict per row. Reads the campaign CSVs that tables.py/paper-tables.py write and the Decide outputs
(conf-join --merge --decide, plan/case-studies/tikv/decide/*.out); writes tex/tables/eval2/tikv.{csv,tex}.
usage: tikv-table.py <PLDI/tex/tables> <plan/case-studies/tikv/decide>"""
import csv, os, re, sys
TB, DEC = sys.argv[1], sys.argv[2]
SDT = r'\sdt'
def num(x):
    try: return float(x)
    except: return None
def g(n):   # integer with thin-space groups, as the other eval2 tables
    n = int(round(float(n))); s = f"{n:,}".replace(',', r'\,'); return s
def t(x):
    x = float(x); return f"{x:.1f}" if x >= 10 else f"{x:.2f}" if x >= 1 else "<1"
def size_label(size, model, variant):
    sc, a, o, at = size.split(',')
    lab = sc + (' async' if a == '1' else '') + (' 1PC' if o == '1' else '')
    if variant not in ('correct', ''): lab += ', ' + variant
    return lab + (r'$^{\mathrm{B}}$' if model in ('bag', 'asyn') else '')
def decide(size, model, variant):
    v = '' if variant == 'correct' else '_' + variant
    f = f"{DEC}/C3J.tikv-txn-rust.impl_{size.replace(',', '_')}_{model}{v}.cinf.m.out"
    if not os.path.exists(f): return None
    for l in open(f):
        m = re.match(r'decide: uncovered=(\d+) violations=(\d+) false_alarms=(\d+) unresolved=(\d+)', l)
        if m: return tuple(int(x) for x in m.groups())
    return None
rows = []
# Rust port vs S_dt: campaign-offline-tf.csv (program tikv-txn-rust)
for r in csv.DictReader(open(f"{TB}/campaign-offline-tf.csv")):
    if r['program'] != 'tikv-txn-rust': continue
    d = decide(r['size'], r['model'], r['variant'])
    rows.append(dict(pair='rust-sdt', size=r['size'], model=r['model'], variant=r['variant'], tools=r'\tf\ / \tf', gc=r['impl graphs'], gr=r['spec graphs'], gx=r['uncovered'], T=r['wall s'], M=r['peak MB'], verdict=r['verdict'], real=d[1] if d else '', false=d[2] if d else '', unresolved=d[3] if d else ''))
# Java port vs S_dt: cross-application-{conf,viol}-full.csv (program tikv-txn, impl Java)
for kind in ('conf', 'viol'):
    for r in csv.DictReader(open(f"{TB}/cross-application-{kind}-full.csv")):
        if r['program'] != 'tikv-txn' or r['impl'] != 'Java': continue
        gx = r.get('G x', '') if kind == 'viol' else '0'
        if kind == 'viol' and not gx:   # the viol CSV has an unnamed uncovered column after G spec
            vals = list(r.values()); gx = vals[8]
        rows.append(dict(pair='java-sdt', size=r['size'], model=r['model'], variant=r['variant'], tools=r'\jmc\ / \tf', gc=r['G impl'], gr=r['G spec'], gx=gx, T=r['offline s'], M=r['offline MB'], verdict='violation' if kind == 'viol' else 'conforms', real='', false='', unresolved=''))
# the two ports against each other: campaign-cftwin-offline-{rust,java}-spec.csv (program tikv-txn)
for f, pair, tools in (('rust-spec', 'java-rust', r'\jmc\ / \tf'), ('java-spec', 'rust-java', r'\tf\ / \jmc')):
    for r in csv.DictReader(open(f"{TB}/campaign-cftwin-offline-{f}.csv")):
        if r['program'] != 'tikv-txn': continue
        rows.append(dict(pair=pair, size=r['size'], model=r['model'], variant=r['variant'], tools=tools, gc=r['impl graphs'], gr=r['spec graphs'], gx=r['uncovered'] or '0', T=r['wall s'], M=r['peak MB'], verdict=r['verdict'], real='', false='', unresolved=''))
ORDER = ['S1', 'X2', 'X2r', 'P2', 'M2', 'L1', 'A3']
def key(r):
    sc, a, o, at = r['size'].split(','); return (ORDER.index(sc), r['model'] != 'fifo', o, a, r['variant'] != 'correct', r['variant'])
PAIRS = [('rust-sdt', r'TiKV port (Rust) $\sqsubseteq$ ' + SDT), ('java-sdt', r'TiKV port (Java) $\sqsubseteq$ ' + SDT), ('java-rust', r'TiKV port (Java) $\sqsubseteq$ TiKV port (Rust)'), ('rust-java', r'TiKV port (Rust) $\sqsubseteq$ TiKV port (Java)')]
os.makedirs(f"{TB}/eval2", exist_ok=True)
with open(f"{TB}/eval2/tikv.csv", 'w', newline='') as fh:
    w = csv.writer(fh); w.writerow(['pair', 'size', 'model', 'variant', 'tools', 'G cand', 'G ref', 'G x', 'offline s', 'offline MB', 'verdict', 'decide violations', 'decide false alarms', 'decide unresolved'])
    for p, _ in PAIRS:
        for r in sorted([x for x in rows if x['pair'] == p], key=key): w.writerow([r['pair'], r['size'], r['model'], r['variant'], r['tools'], r['gc'], r['gr'], r['gx'], r['T'], r['M'], r['verdict'], r['real'], r['false'], r['unresolved']])
L = [r'% tab:eval2:tikv -- generated by daavar/scripts/tikv-table.py from the campaign CSVs and the Decide outputs (plan/case-studies/tikv/decide); do not edit',
     r'\begin{table}[tp]',
     r'\caption{The TiKV transaction port against \sdt\ and the two ports against each other, candidate $\sqsubseteq$ reference, \offline. The size is the scenario of the study (clients, keys and scripts), with async commit, 1PC and the two injected faults f1, f2 where marked; B = bag delivery, otherwise fifo. $G_x$ = uncovered summaries; the last two columns are the verdict of the Decide post-pass on them: witnesses found (violations) and false alarms.}',
     r'\label{tab:eval2:tikv}', r'\scriptsize\setlength{\tabcolsep}{3pt}\centering', r'\begin{tabular}{@{}lllrrrrrrr@{}}', r'\toprule',
     r' & & & & & & \multicolumn{2}{c}{\offline} & \multicolumn{2}{c}{Decide} \\', r'\cmidrule(lr){7-8}\cmidrule(lr){9-10}',
     r'pair & size & tools & $G_{\mathit{cand}}$ & $G_{\mathit{ref}}$ & $G_x$ & T & M & viol. & false \\', r'\midrule']
first = True
for p, name in PAIRS:
    rs = sorted([x for x in rows if x['pair'] == p], key=key)
    if not rs: continue
    if not first: L.append(r'\midrule')
    first = False
    for i, r in enumerate(rs):
        dv = str(r['real']) if r['real'] != '' else ''; df = str(r['false']) if r['false'] != '' else ''
        if int(float(r['gx'] or 0)) == 0: dv, df = '', ''
        L.append(f"{name if i == 0 else ''} & {size_label(r['size'], r['model'], r['variant'])} & {r['tools']} & {g(r['gc'])} & {g(r['gr'])} & {g(r['gx'] or 0)} & {t(r['T'])} & {g(r['M'])} & {dv} & {df} \\\\")
L += [r'\bottomrule', r'\end{tabular}', r'\end{table}']
open(f"{TB}/eval2/tikv.tex", 'w').write('\n'.join(L) + '\n'); print('tikv table:', len(rows), 'rows')
